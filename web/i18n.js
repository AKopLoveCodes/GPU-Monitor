  const normalize = (value) => (value === 'en' ? 'en' : FALLBACK);
  const fromQuery = new URLSearchParams(location.search).get('lang');
  let lang;
  try { lang = normalize(localStorage.getItem(STORAGE_KEY)); } catch { lang = FALLBACK; }
  if (fromQuery) lang = normalize(fromQuery);

  const listeners = new Set();

  function t(key, params) {
    let text = MESSAGES[lang][key] ?? MESSAGES[FALLBACK][key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) text = text.split(`{${name}}`).join(value);
    }
    return text;
  }

  function applyStatic(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = t(node.dataset.i18n); });
    root.querySelectorAll('[data-i18n-title]').forEach(node => { node.title = t(node.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-aria]').forEach(node => { node.setAttribute('aria-label', t(node.dataset.i18nAria)); });
    document.documentElement.lang = lang;
    document.title = t('doc.title');
    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', t('doc.description'));
  }

  function setLang(next) {
    const value = normalize(next);
    if (value === lang) return;
    lang = value;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* Language still switches for this page. */ }
    applyStatic();
    listeners.forEach(listener => listener(lang));
  }

